#!/usr/bin/env python3
"""Create small original PDF fixtures without downloading document content.

The expected text/order is authored here, independently from the layout engine.
More demanding geometry fixtures are added as their adapters are implemented.
"""
import json
from pathlib import Path

from common import ROOT


def write_pdf(path, pages):
    objects = [b"<< /Type /Catalog /Pages 2 0 R >>", b"",
               b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"]
    kids = []
    for page in pages:
        page_id, stream_id = len(objects) + 1, len(objects) + 2
        kids.append(str(page_id) + " 0 R")
        commands = []
        for x, y, size, text in page:
            escaped = text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
            commands.append(f"BT /F1 {size} Tf {x} {y} Td ({escaped}) Tj ET")
        stream = ("\n".join(commands) + "\n").encode("ascii")
        objects.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R >> >> /Contents {stream_id} 0 R >>".encode())
        objects.append(f"<< /Length {len(stream)} >>\nstream\n".encode() + stream + b"endstream")
    objects[1] = f"<< /Type /Pages /Count {len(kids)} /Kids [{' '.join(kids)}] >>".encode()
    data = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for index, obj in enumerate(objects, 1):
        offsets.append(len(data))
        data.extend(f"{index} 0 obj\n".encode() + obj + b"\nendobj\n")
    xref = len(data)
    data.extend(f"xref\n0 {len(offsets)}\n0000000000 65535 f \n".encode())
    for offset in offsets[1:]: data.extend(f"{offset:010d} 00000 n \n".encode())
    data.extend(f"trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def main():
    root = ROOT / "tests/fixtures"
    pages = [
        [(48, 736, 22, "Offline PDF Translator"),
         (48, 696, 12, "The device has 3 sensors. It does not use the network."),
         (48, 678, 12, "The source document remains unchanged."),
         (48, 636, 12, "A second paragraph checks paragraph boundaries."),
         (48, 618, 12, "Visible hyphens, such as re-enter, must be preserved.")],
        [(48, 736, 22, "A second page"),
         (48, 696, 12, "Reading and translation refer to the same physical page."),
         (48, 678, 12, "There are 12 samples in the experiment.")],
        [],
    ]
    write_pdf(root / "P01-simple.pdf", pages)
    expected = {"origin": "Original synthetic content, generated by scripts/generate_fixtures.py",
                "P01-simple.pdf": {"page_count": 3,
                    "reading_order": [[line[3] for line in p] for p in pages],
                    "no_text_pages": [2], "media_box": [0, 0, 612, 792]}}
    (root / "pdf-ground-truth.json").write_text(json.dumps(expected, indent=2) + "\n")


if __name__ == "__main__":
    main()
