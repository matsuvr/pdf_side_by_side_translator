#!/usr/bin/env python3
"""Embed original help/icon and verified notices; no runtime file dependency."""
import argparse
from pathlib import Path

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();root=Path(__file__).resolve().parents[1]
    inputs={'help':root/'resources/help-ja.txt','licenses':root/'THIRD_PARTY_NOTICES.txt','icon_png':root/'resources/app-icon.png'}
    lines=['// Generated by scripts/embed_resources.py. Do not edit.','#include "app/resources.hpp"','namespace opt::resources {','namespace {']
    for name,path in inputs.items():
        data=path.read_bytes();lines.append(f'constexpr unsigned char {name}_data[]={{')
        lines.extend(','.join(str(n) for n in data[i:i+32])+',' for i in range(0,len(data),32))
        lines.append('};')
    lines.append('}')
    for name in inputs:
        if name=='icon_png':lines.append('std::span<const unsigned char> icon_png(){return icon_png_data;}')
        else:lines.append(f'std::string_view {name}(){{return {{reinterpret_cast<const char*>({name}_data),sizeof({name}_data)}};}}')
    lines.append('}')
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
if __name__=='__main__':main()
