#!/usr/bin/env python3
"""Write a content-stable build identity without paths, user names or secrets."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT=Path(__file__).resolve().parents[1]
def source_identity():
    commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
    status=subprocess.check_output(['git','status','--porcelain','--untracked-files=normal'],cwd=ROOT)
    names=subprocess.check_output(['git','ls-files','-z'],cwd=ROOT).split(b'\0')
    digest=hashlib.sha256()
    for name in sorted(n for n in names if n):
        path=ROOT/name.decode('utf-8');data=path.read_bytes() if path.is_file() else b'<missing>'
        digest.update(len(name).to_bytes(8,'little'));digest.update(name);digest.update(len(data).to_bytes(8,'little'));digest.update(data)
    return {'commit':commit,'dirty':bool(status),'source_sha256':digest.hexdigest()}
def build_info(target,version):
    result={'schema':1,'product':'Offline PDF Translator','version':version,'target':target,**source_identity()}
    for name in ['third_party.lock.json','licenses.lock.json']:
        result[name+'_sha256']=hashlib.sha256((ROOT/'deps'/name).read_bytes()).hexdigest()
    result['identity_sha256']=hashlib.sha256(json.dumps(result,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    return result
def write_changed(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    if not path.exists() or path.read_bytes()!=data:path.write_bytes(data)
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--target',required=True);parser.add_argument('--version',required=True)
    parser.add_argument('--header',type=Path,required=True);parser.add_argument('--json',type=Path,required=True);args=parser.parse_args()
    info=build_info(args.target,args.version)
    header=f'''// Generated by scripts/write_build_info.py.
#pragma once
namespace opt::build {{
inline constexpr auto revision="{info['commit']}";
inline constexpr bool dirty={'true' if info['dirty'] else 'false'};
inline constexpr auto identity="OPT_BUILD_INFO:{info['identity_sha256']}";
}}
'''
    write_changed(args.header,header.encode());write_changed(args.json,(json.dumps(info,indent=2)+'\n').encode())
if __name__=='__main__':main()
